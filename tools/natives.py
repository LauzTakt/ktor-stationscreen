"""Natives implemented in C by the firmware, read from runtime/natives.txt.

Each entry is a JVM method key "owner.name(descriptor)". The index in this list
is the native id. `python3 tools/natives.py` regenerates firmware/src/natives_gen.h.
Array methods use the pseudo-owner "[".
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from classfile import arg_slots, ret_slots  # noqa: E402

_NATIVES_TXT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "runtime", "natives.txt")
with open(_NATIVES_TXT) as _f:
    NATIVES = [l.strip() for l in _f if l.strip() and not l.strip().startswith("#")]

NATIVE_IDS = {k: i for i, k in enumerate(NATIVES)}
assert len(NATIVE_IDS) == len(NATIVES), "duplicate native"


def split_key(k):
    owner, rest = k.split(".", 1)
    name, desc = rest[:rest.index("(")], rest[rest.index("("):]
    return owner, name, desc


def is_static_native(k):
    """Natives on String/Object/[ are instance methods unless named valueOf."""
    owner, name, _ = split_key(k)
    if owner in ("java/lang/Object", "java/lang/String", "["):
        return name == "valueOf"
    return True  # ktvm/Native and esp32 natives are static


def c_ident(k):
    s = k.replace("<init>", "init").replace("[", "A")
    return "N_" + re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_")


def generate_header(path):
    lines = ["// GENERATED by tools/natives.py -- do not edit", "#pragma once", "#include <stdint.h>", "",
             "enum NativeId {"]
    for i, k in enumerate(NATIVES):
        lines.append(f"  {c_ident(k)} = {i},")
    lines += [f"  N_COUNT = {len(NATIVES)}", "};", ""]
    lines.append("static const uint8_t native_argslots[] = {")
    for k in NATIVES:
        _, _, d = split_key(k)
        lines.append(f"  {arg_slots(d) + (0 if is_static_native(k) else 1)}, // {k}")
    lines += ["};", "static const uint8_t native_retslots[] = {"]
    for k in NATIVES:
        _, _, d = split_key(k)
        lines.append(f"  {ret_slots(d)},")
    lines += ["};", "static const char* const native_names[] = {"]
    for k in NATIVES:
        lines.append(f'  "{k}",')
    lines += ["};", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "firmware", "src", "natives_gen.h")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    generate_header(out)
    print("wrote", out)
